// Portfolio exports: XLSX takeoff workbook, KML and GeoJSON.

import { milepostMarkers, tableColumns } from '../pi-engine';
import type { FeatureCalc, PortfolioCalc } from './calc';
import type { Portfolio, SubProject, TakeoffFeature } from './types';
import { LEN_CODE, LONG_CODE, MP_PREFIX, PER_LONG, smallAreaFromM2, SMALL_AREA_CODE, staExact, UNIT_OPTIONS } from './units';
import { writeXlsx, type Cell } from './xlsx';

const r = (x: number | null | undefined, d: number): number | null => (x === null || x === undefined || !Number.isFinite(x) ? null : Number(x.toFixed(d)));

export const safeName = (s: string) => s.replace(/[^\w.-]+/g, '_').replace(/_+/g, '_').replace(/^_|_$/g, '') || 'portfolio';

export function exportBaseName(p: Portfolio): string {
  return safeName([p.number, p.name].filter(Boolean).join('_'));
}

interface FeatureRow {
  f: TakeoffFeature;
  sub: SubProject;
  subNo: number;
  c: FeatureCalc;
}

function featureRows(p: Portfolio, calc: PortfolioCalc): FeatureRow[] {
  const subIndex = new Map(p.subprojects.map((s, i) => [s.id, i]));
  return p.features
    .filter((f) => calc.features.has(f.id) && subIndex.has(f.subId))
    .map((f) => ({ f, sub: p.subprojects[subIndex.get(f.subId)!], subNo: subIndex.get(f.subId)! + 1, c: calc.features.get(f.id)! }))
    .sort((a, b) => a.subNo - b.subNo || (a.c.beginSta ?? 1e15) - (b.c.beginSta ?? 1e15) || a.f.id.localeCompare(b.f.id));
}

/** One set of feature attributes, shared by XLSX, KML popups and GeoJSON properties. */
function featureAttrs(p: Portfolio, calc: PortfolioCalc, row: FeatureRow): [string, Cell][] {
  const { f, sub, subNo, c } = row;
  const it = calc.items.get(f.code);
  const u = p.units;
  const mp = MP_PREFIX(u);
  return [
    ['FEATURE_ID', f.id],
    ['SUBPROJECT_NO', subNo],
    ['SUBPROJECT', sub.name],
    ['SUBPROJECT_NUMBER', sub.number],
    ['ITEM_CODE', f.code],
    ['CATEGORY', it?.category ?? ''],
    ['ITEM', it?.name ?? ''],
    ['NAME', f.name],
    ['GEOMETRY', f.kind],
    ['QUANTITY', r(c.qty, f.kind === 'Polygon' ? 4 : 2)],
    ['UNIT', c.unit],
    ['AREA_' + SMALL_AREA_CODE(u), f.kind === 'Polygon' ? r(smallAreaFromM2(c.areaM2, u), 1) : null],
    ['BEGIN_STATION', r(c.beginSta, 2)],
    ['END_STATION', r(c.endSta, 2)],
    ['BEGIN_STA_TEXT', c.beginSta === null ? '' : staExact(c.beginSta, u)],
    ['END_STA_TEXT', c.endSta === null ? '' : staExact(c.endSta, u)],
    [`BEGIN_${mp}`, r(c.beginMp, 3)],
    [`END_${mp}`, r(c.endMp, 3)],
    ['OFFSET_' + LEN_CODE[u], r(c.offset, 1)],
    ['SIDE', c.side],
    ['LATITUDE', r(c.lat, 8)],
    ['LONGITUDE', r(c.lon, 8)],
    ['START_LATITUDE', f.kind === 'Line' ? r(c.startLat, 8) : null],
    ['START_LONGITUDE', f.kind === 'Line' ? r(c.startLon, 8) : null],
    ['END_LATITUDE', f.kind === 'Line' ? r(c.endLat, 8) : null],
    ['END_LONGITUDE', f.kind === 'Line' ? r(c.endLon, 8) : null],
    ['FLAG', c.flag],
    ['NOTES', f.notes],
  ];
}

export function portfolioXlsx(p: Portfolio, calc: PortfolioCalc): Uint8Array {
  const u = p.units;
  const unitLabel = UNIT_OPTIONS.find((o) => o.value === u)?.label ?? u;
  const mp = MP_PREFIX(u);
  const rows = featureRows(p, calc);

  const info: Cell[][] = [
    ['Portfolio name', p.name],
    ['Portfolio number', p.number],
    ['Units', unitLabel],
    ['Length unit', LEN_CODE[u]],
    ['Exported', new Date().toISOString().replace('T', ' ').slice(0, 16) + ' UTC'],
    ['Sub-projects', p.subprojects.length],
    ['Features', p.features.length],
    ['Off-centerline flag limit (ft)', p.offsetLimitFt],
    ['Measurement', 'Geodesic lengths on WGS84 (Vincenty); areas on the authalic sphere; stations by projection onto each sub-project centerline'],
    ['Generated by', 'GeoEstimator'],
  ];

  const subs: Cell[][] = calc.subs.map((s, i) => [
    i + 1, s.sub.name, s.sub.number, p.industry ?? '', s.sub.commodity, s.sub.size, s.sub.material, s.sub.scope,
    s.sub.location, s.sub.terrain, s.sub.costYear, s.sub.centerlineName,
    r(s.ref?.length, 2), r(s.ref ? s.ref.length / PER_LONG(u) : null, 3),
    s.pi ? s.pi.rows.filter((x) => x.kind === 'PI').length : null,
    p.industry === 'Pipeline' && s.pi ? s.pi.counts['FIELD BEND'] : null,
    p.industry === 'Pipeline' && s.pi ? s.pi.counts.FITTING : null,
    s.featureCount,
  ]);

  const summary: Cell[][] = [];
  calc.subs.forEach((s, i) => {
    for (const t of s.items) {
      summary.push([i + 1, s.sub.name, s.sub.number, p.industry ?? '', s.sub.size, s.sub.material, t.code, t.item?.category ?? '', t.item?.name ?? '(not in catalog)', t.item?.geometry ?? '', r(t.qty, t.unit === 'EA' ? 0 : t.item?.geometry === 'Polygon' ? 4 : 2), t.unit, t.count]);
    }
  });

  const attrs = rows.map((row) => featureAttrs(p, calc, row));
  const detailHeader = attrs[0]?.map(([k]) => k) ?? featureAttrs(p, calc, {
    f: { id: '', subId: '', code: '', kind: 'Line', coords: [[0, 0]], name: '', notes: '', created: '', modified: '' },
    sub: p.subprojects[0], subNo: 1,
    c: { id: '', qty: 0, unit: '', areaM2: 0, beginSta: null, endSta: null, beginMp: null, endMp: null, station: null, mp: null, offset: null, side: '', lat: 0, lon: 0, startLat: 0, startLon: 0, endLat: 0, endLon: 0, flag: '' },
  }).map(([k]) => k);

  const piRows: Cell[][] = [];
  let piHeader: string[] = ['SUBPROJECT_NO', 'SUBPROJECT'];
  calc.subs.forEach((s, i) => {
    if (!s.pi) return;
    const cols = tableColumns(s.pi);
    piHeader = ['SUBPROJECT_NO', 'SUBPROJECT', ...cols.map((c) => c.header)];
    const pipeline = p.industry === 'Pipeline';
    for (const row of s.pi.rows) {
      piRows.push([i + 1, s.sub.name, ...cols.map((c) => (!pipeline && (c.key === 'bendType' || c.key === 'fittingNo') ? null : c.get(row)))]);
    }
  });

  const L = LEN_CODE[u];
  return writeXlsx([
    { name: 'Portfolio', header: ['Field', 'Value'], rows: info, widths: [30, 90] },
    {
      name: 'Sub-Projects',
      header: ['NO', 'NAME', 'NUMBER', 'INDUSTRY', 'COMMODITY', 'SIZE', 'MATERIAL', 'SCOPE', 'LOCATION', 'TERRAIN', 'COST_BASIS_YEAR', 'CENTERLINE', `CL_LENGTH_${L}`, `CL_LENGTH_${LONG_CODE(u)}`, 'PI_COUNT', 'FIELD_BENDS', 'FITTING_PIS', 'FEATURES'],
      rows: subs,
    },
    {
      name: 'Quantity Summary',
      header: ['SUBPROJECT_NO', 'SUBPROJECT', 'SUBPROJECT_NUMBER', 'INDUSTRY', 'SIZE', 'MATERIAL', 'ITEM_CODE', 'CATEGORY', 'ITEM', 'GEOMETRY', 'QUANTITY', 'UNIT', 'FEATURE_COUNT'],
      rows: summary,
      widths: [14, 22, 18, 11, 10, 16, 12, 14, 30, 10, 12, 8, 14],
    },
    { name: 'Feature Detail', header: detailHeader, rows: attrs.map((a) => a.map(([, v]) => v)) },
    { name: 'PI Table', header: piHeader, rows: piRows },
  ].map((s) => (s.name === 'PI Table' && !piRows.length ? { ...s, header: ['NOTE'], rows: [[`No centerlines loaded. ${mp} and PI data appear here once a route is uploaded.`]] } : s)));
}

// ---------------------------------------------------------------- KML

const x = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
const h = (s: string) => s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/]]>/g, ']] >');

/** #RRGGBB → KML aabbggrr */
function kmlColor(hex: string, alpha = 'ff'): string {
  const m = hex.replace('#', '').padEnd(6, '0');
  return alpha + m.slice(4, 6) + m.slice(2, 4) + m.slice(0, 2);
}

const coordText = (c: [number, number][]) => c.map(([lon, lat]) => `${lon.toFixed(9)},${lat.toFixed(9)},0`).join(' ');

export function portfolioKml(p: Portfolio, calc: PortfolioCalc): string {
  const u = p.units;
  const mpPre = MP_PREFIX(u);
  const rows = featureRows(p, calc);
  const styles: string[] = [];
  const styleIds = new Set<string>();
  const addStyle = (id: string, body: string) => { if (!styleIds.has(id)) { styleIds.add(id); styles.push(`<Style id="${id}">${body}</Style>`); } };
  const dot = 'http://maps.google.com/mapfiles/kml/shapes/placemark_circle.png';

  const table = (pairs: [string, Cell][]) =>
    '<![CDATA[<table style="font-family:Arial;font-size:12px">' +
    pairs.filter(([, v]) => v !== null && v !== undefined && v !== '').map(([k, v]) => `<tr><td><b>${k}</b></td><td>${h(String(v))}</td></tr>`).join('') +
    '</table>]]>';
  const ext = (pairs: [string, Cell][]) =>
    '<ExtendedData>' + pairs.map(([k, v]) => `<Data name="${k}"><value>${v === null || v === undefined ? '' : x(String(v))}</value></Data>`).join('') + '</ExtendedData>';

  const folders: string[] = [];
  calc.subs.forEach((s, i) => {
    const sub = s.sub;
    const parts: string[] = [];
    if (s.pi && s.ref) {
      const sid = `cl${i}`;
      addStyle(sid, `<LineStyle><color>${kmlColor(sub.color)}</color><width>3</width></LineStyle>`);
      const clCoords = s.pi.rows.map((row) => [row.lon, row.lat] as [number, number]);
      parts.push(`<Placemark><name>${x(sub.centerlineName || sub.name)} centerline</name><styleUrl>#${sid}</styleUrl>${ext([['SUBPROJECT', sub.name], ['LENGTH_' + LEN_CODE[u], r(s.ref.length, 2)]])}<LineString><tessellate>1</tessellate><coordinates>${coordText(clCoords)}</coordinates></LineString></Placemark>`);
      addStyle('mp', `<IconStyle><color>ffffffff</color><scale>0.9</scale><Icon><href>http://maps.google.com/mapfiles/kml/pushpin/ylw-pushpin.png</href></Icon><hotSpot x="20" y="2" xunits="pixels" yunits="pixels"/></IconStyle><LabelStyle><color>ff00ffff</color><scale>0.8</scale></LabelStyle>`);
      const mps = milepostMarkers(s.pi, p.mpInterval);
      const dec = p.mpInterval < 1 ? 1 : 0;
      parts.push(`<Folder><name>${mpPre === 'KP' ? 'Kiloposts' : 'Mileposts'}</name>` + mps.map((m) => `<Placemark><name>${mpPre} ${m.mp.toFixed(dec)}</name><styleUrl>#mp</styleUrl><Point><coordinates>${m.lon.toFixed(9)},${m.lat.toFixed(9)},0</coordinates></Point></Placemark>`).join('') + '</Folder>');
      addStyle('pi', `<IconStyle><color>ffb4b4b4</color><scale>0.6</scale><Icon><href>${dot}</href></Icon></IconStyle><LabelStyle><scale>0</scale></LabelStyle>`);
      const pis = s.pi.rows.filter((row) => row.kind === 'PI');
      parts.push(`<Folder><name>PIs (${pis.length})</name><visibility>0</visibility>` + pis.map((row) => `<Placemark><name>${x(row.label)}</name><visibility>0</visibility><styleUrl>#pi</styleUrl><description>${x(row.fullLabel)}</description><Point><coordinates>${row.lon.toFixed(9)},${row.lat.toFixed(9)},0</coordinates></Point></Placemark>`).join('') + '</Folder>');
    }
    const byCode = new Map<string, FeatureRow[]>();
    for (const row of rows) if (row.sub.id === sub.id) (byCode.get(row.f.code) ?? byCode.set(row.f.code, []).get(row.f.code)!).push(row);
    for (const [code, list] of byCode) {
      const it = calc.items.get(code);
      const color = it?.color ?? '#868E96';
      const sid = `it_${code.replace(/[^\w-]/g, '_')}`;
      addStyle(sid,
        `<IconStyle><color>${kmlColor(color)}</color><scale>${Math.max(0.5, (it?.size ?? 8) / 10).toFixed(2)}</scale><Icon><href>${dot}</href></Icon></IconStyle>` +
        `<LabelStyle><scale>0.7</scale></LabelStyle><LineStyle><color>${kmlColor(color)}</color><width>${it?.size ?? 3}</width></LineStyle><PolyStyle><color>${kmlColor(color, '55')}</color></PolyStyle>`);
      const marks = list.map((row) => {
        const attrs = featureAttrs(p, calc, row);
        const nm = row.f.name || `${code} ${row.f.id}`;
        const geom =
          row.f.kind === 'Point' ? `<Point><coordinates>${coordText(row.f.coords)}</coordinates></Point>`
          : row.f.kind === 'Line' ? `<LineString><tessellate>1</tessellate><coordinates>${coordText(row.f.coords)}</coordinates></LineString>`
          : `<Polygon><tessellate>1</tessellate><outerBoundaryIs><LinearRing><coordinates>${coordText([...row.f.coords, row.f.coords[0]])}</coordinates></LinearRing></outerBoundaryIs></Polygon>`;
        return `<Placemark><name>${x(nm)}</name><styleUrl>#${sid}</styleUrl><description>${table(attrs)}</description>${ext(attrs)}${geom}</Placemark>`;
      });
      parts.push(`<Folder><name>${x(code)} ${x(it?.name ?? '')} (${list.length})</name>${marks.join('')}</Folder>`);
    }
    folders.push(`<Folder><name>${i + 1}. ${x(sub.name)}${sub.number ? ' (' + x(sub.number) + ')' : ''}</name><open>1</open>${parts.join('')}</Folder>`);
  });

  return (
    '<?xml version="1.0" encoding="UTF-8"?>\n<kml xmlns="http://www.opengis.net/kml/2.2"><Document>' +
    `<name>${x(p.name)}${p.number ? ' (' + x(p.number) + ')' : ''}</name><open>1</open>` +
    styles.join('') + folders.join('') +
    '</Document></kml>\n'
  );
}

// ---------------------------------------------------------------- GeoJSON

export function portfolioGeoJson(p: Portfolio, calc: PortfolioCalc): string {
  const u = p.units;
  const features: object[] = [];
  calc.subs.forEach((s, i) => {
    if (!s.pi || !s.ref) return;
    features.push({
      type: 'Feature',
      properties: { FEATURE_TYPE: 'CENTERLINE', SUBPROJECT_NO: i + 1, SUBPROJECT: s.sub.name, NAME: s.sub.centerlineName, ['LENGTH_' + LEN_CODE[u]]: r(s.ref.length, 2), UNITS: LEN_CODE[u] },
      geometry: { type: 'LineString', coordinates: s.pi.rows.map((row) => [row.lon, row.lat]) },
    });
    const cols = tableColumns(s.pi);
    for (const row of s.pi.rows.filter((x) => x.kind === 'PI')) {
      features.push({
        type: 'Feature',
        properties: { FEATURE_TYPE: 'PI', SUBPROJECT_NO: i + 1, SUBPROJECT: s.sub.name, ...Object.fromEntries(cols.map((c) => [c.header, c.get(row)])) },
        geometry: { type: 'Point', coordinates: [row.lon, row.lat] },
      });
    }
  });
  for (const row of featureRows(p, calc)) {
    const props = Object.fromEntries([['FEATURE_TYPE', 'TAKEOFF'], ...featureAttrs(p, calc, row)]);
    const c = row.f.coords;
    const geometry =
      row.f.kind === 'Point' ? { type: 'Point', coordinates: c[0] }
      : row.f.kind === 'Line' ? { type: 'LineString', coordinates: c }
      : { type: 'Polygon', coordinates: [[...c, c[0]]] };
    features.push({ type: 'Feature', id: row.f.id, properties: props, geometry });
  }
  return JSON.stringify({ type: 'FeatureCollection', name: p.name, features }, null, 1);
}
